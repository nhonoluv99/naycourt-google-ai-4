/**
 * Tìm kiếm trực tiếp thời gian thực từ cơ sở dữ liệu PVNA (Ảnh 1 & 2)
 */
export async function searchLivePvnaPlayers(queryText: string): Promise<RatedPlayer[]> {
  const q = queryText.trim();
  if (!q) return [];
  try {
    const res = await fetch(`/api/pvna-proxy?search=${encodeURIComponent(q)}&page=0&limit=30`);
    if (!res.ok) return [];
    const data = await res.json();
    if (!data.success || !data.data?.players) return [];

    return data.data.players.map((item: any): RatedPlayer => {
      const pDoubles = Number(item.doubleScore ?? item.hardScoreDouble ?? 2.1);
      const pSingles = Number(item.singleScore ?? item.hardScoreSingle ?? 2.1);
      const dDoubles = Number((pDoubles > 2.0 ? pDoubles + 0.05 : pDoubles).toFixed(3));
      const dSingles = Number((pSingles > 2.0 ? pSingles : 2.1).toFixed(3));

      const cityName = item.city ? (CITY_NAMES[item.city] || item.city) : "Việt Nam";

      return {
        id: `pvna_live_${item.id || item.playerCode}`,
        name: item.name || item.nickName || "VĐV",
        gender: item.gender === "female" ? "nu" : "nam",
        club: `${cityName} Pickleball`,
        province: cityName,
        duprDoubles: dDoubles,
        duprSingles: dSingles,
        pvnaDoubles: pDoubles,
        pvnaSingles: pSingles,
        duprRating: dDoubles,
        pvnaRating: pDoubles,
        pvnaId: item.playerCode || "",
        duprId: item.playerCode ? `PVNA-${item.playerCode}` : "",
        verified: true,
      };
    });
  } catch (e) {
    console.debug("Live PVNA search fetch error:", e);
    return [];
  }
}
