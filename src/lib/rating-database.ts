/**
 * Tìm kiếm VĐV chính thức từ hệ thống DUPR và PVNA.
 * Nếu không có người trùng khớp, trả về mảng rỗng [] (không tự bịa tên/điểm).
 */
export function searchRatedPlayers(
  query: string,
  options?: {
    gender?: "nam" | "nu";
    limit?: number;
  }
): RatedPlayer[] {
  const normQuery = normalizeVietnamese(query);

  const list = OFFICIAL_PLAYERS.filter((player) => {
    if (normQuery) {
      const matchName = normalizeVietnamese(player.name).includes(normQuery);
      const matchPvnaId = player.pvnaId ? normalizeVietnamese(player.pvnaId).includes(normQuery) : false;
      const matchDuprId = player.duprId ? normalizeVietnamese(player.duprId).includes(normQuery) : false;
      if (!matchName && !matchPvnaId && !matchDuprId) return false;
    }
    if (options?.gender && player.gender !== options.gender) return false;
    return true;
  });

  return list.slice(0, options?.limit ?? 50);
}

