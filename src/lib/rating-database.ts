/**
 * HỆ THỐNG TRA CỨU ĐIỂM DUPR / PVNA PICKLEBALL
 * 
 * 1. DUPR: Hệ thống xếp hạng toàn cầu chính thức (Dynamic Universal Pickleball Rating)
 *    - DUPR Đôi (Doubles): Thang điểm 2.000 - 6.500+
 *    - DUPR Đơn (Singles): Thang điểm 2.000 - 6.500+
 * 2. PVNA: Hệ thống xếp hạng Pickleball Việt Nam chính thức
 *    - PVNA Đôi (Doubles): Thang điểm 2.000 - 5.500+
 *    - PVNA Đơn (Singles): Thang điểm 2.000 - 5.500+
 */

export interface RatedPlayer {
  id: string;
  name: string;
  gender: "nam" | "nu";
  club?: string;
  province?: string;
  // DUPR (DURP)
  duprDoubles: number; // Điểm DUPR Đôi thực
  duprSingles: number; // Điểm DUPR Đơn thực
  // PVNA
  pvnaDoubles: number; // Điểm PVNA Đôi thực
  pvnaSingles: number; // Điểm PVNA Đơn thực
  // Alias / tương thích
  duprRating: number;
  pvnaRating: number;
  pvnaId?: string;
  duprId?: string;
  verified?: boolean;
}

export function normalizeVietnamese(str: string): string {
  if (!str) return "";
  return str
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/đ/g, "d")
    .replace(/Đ/g, "d")
    .trim();
}

