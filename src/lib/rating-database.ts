/**
 * HỆ THỐNG TRA CỨU ĐIỂM DUPR / PVNA PICKLEBALL CHÍNH THỨC
 * 
 * 1. DUPR: Hệ thống xếp hạng toàn cầu chính thức (Dynamic Universal Pickleball Rating)
 *    - Các siêu sao thế giới (Ben Johns, Federico Staksrud, Anna Leigh Waters...) và VĐV Việt Nam có điểm DUPR.
 *    - Thang điểm DUPR: 2.000 - 8.000
 *    - Bảng DUPR KHÔNG hiển thị tích xác thực.
 * 
 * 2. PVNA: Hệ thống xếp hạng Pickleball Việt Nam chính thức (pvna.vn)
 *    - Chỉ dành cho VĐV trong hệ thống PVNA (Việt Nam).
 *    - Các VĐV quốc tế (Ben Johns, Anna Leigh Waters...) KHÔNG CÓ TRÊN PVNA.
 *    - Hiển thị dấu tích chính thức theo dữ liệu PVNA:
 *      + Tích vàng (yellow): VĐV chuyên nghiệp / hạt giống hàng đầu
 *      + Tích xanh (green / blue): VĐV đã xác minh trình độ chính thức
 *      + Tích xám (gray): VĐV đăng ký thông thường
 */

export interface RatedPlayer {
  id: string;
  name: string;
  gender: "nam" | "nu";
  club?: string;
  province?: string;
  // DUPR (DURP)
  duprDoubles: number;
  duprSingles: number;
  // PVNA
  pvnaDoubles: number;
  pvnaSingles: number;
  // Thuộc tính hệ thống
  pvnaId?: string;
  duprId?: string;
  tickColor?: "yellow" | "green" | "blue" | "gray" | string;
  tickColorSingle?: string;
  isDuprPlayer?: boolean;
  isPvnaPlayer?: boolean;
  // Tương thích ngược
  duprRating?: number;
  pvnaRating?: number;
  verified?: boolean;
}

export function normalizeVietnamese(str: string): string {
  if (!str) return "";
  return str
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/đ/g, "d")
    .replace(/Đ/g, "d")
    .trim();
}

